function normaliserLigne(l) {
  const r = {};
  for (const [k, v] of Object.entries(l)) {
    const ck = cleEntete(k);
    r[EQUIV_NORM[ck] || ck] = v;
  }
  return r;
}
// Index des équivalences normalisé comme les en-têtes lus (les clés avec
// apostrophes courbes ’ ne matcheraient jamais sinon — cf. cleEntete).
const EQUIV_NORM = {};
for (const [k, v] of Object.entries(EQUIV)) EQUIV_NORM[cleEntete(k)] = v;

